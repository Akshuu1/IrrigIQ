# Verify key parity with en
def get_deep_keys(d, prefix=''):
    keys = []
    for k, v in d.items():
        full = f"{prefix}.{k}" if prefix else k
        if isinstance(v, dict):
            keys.extend(get_deep_keys(v, full))
        else:
            keys.append(full)
    return set(keys)

en_keys = get_deep_keys(en)
mr_keys = get_deep_keys(mr)
pa_keys = get_deep_keys(pa)
te_keys = get_deep_keys(te)

missing_mr = en_keys - mr_keys
missing_pa = en_keys - pa_keys
missing_te = en_keys - te_keys

if missing_mr:
    print(f"Missing in mr: {missing_mr}")
if missing_pa:
    print(f"Missing in pa: {missing_pa}")
if missing_te:
    print(f"Missing in te: {missing_te}")

